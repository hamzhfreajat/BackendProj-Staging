    for q, res in results:
        if "error" in res:
            md.write(f'| {q} | ERROR | ERROR | ERROR | ERROR | ERROR | ERROR | ERROR | ERROR | ERROR | ERROR |\n')
            continue
            
        filters = res.get('filters_applied', {})
        intent = res.get('intent', '-')
        
        cat = filters.get('category_name') or '-'
