        tags = ', '.join(filters.get('tags', [])) if filters.get('tags') else '-'
        
        md.write(f'| {q} | {intent} | {cat} | {locs} | {area} | {price} | {beds} | {baths} | {furn} | {floor} | {tags} |\n')
